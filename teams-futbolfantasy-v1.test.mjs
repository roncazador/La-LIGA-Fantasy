import assert from 'node:assert/strict';
import fs from 'node:fs';
const ui=fs.readFileSync('./teams-data-v4.js','utf8');
const legacy=fs.readFileSync('./teams-futbolfantasy-v1.js','utf8');
const config=fs.readFileSync('./config.mjs','utf8');
const connection=fs.readFileSync('./connection-client.js','utf8');
